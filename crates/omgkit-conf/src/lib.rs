//! **确定性的分子 3D 初始构型生成** —— 给后续力场优化提供一个起点。
//!
//! # 目标,以及**不是**目标
//!
//! 目标:给一个分子生成**一个**三维构型,键长键角基本合理、立体化学正确、
//! 没有原子重叠,**交给后续力场优化**。
//!
//! **不是**目标:构象系综、构象搜索、接近实验结构、MMFF 优化后的几何分布。
//!
//! # 与 RDKit(ETKDG)的分岔点:**去掉随机采样,不是去掉嵌入**
//!
//! RDKit 的流程是:界矩阵 → 三角光滑化 → **在区间里随机取一组距离** →
//! 度量矩阵嵌入 → 误差函数精修 → 不合格就换一组随机距离重来(最多 `10×N` 次)。
//!
//! 病在"随机取一组距离"这一步:每一对原子**各自独立**取值,取出来的表
//! 往往任何空间里都摆不出来 —— 好比"A 离 B 三米、B 离 C 三米、A 离 C 十米",
//! 写得下来,画不出来。RDKit 的应对是作废整次尝试重掷,而当病因是结构性的时候,
//! **`10×N` 次重试会以同样的方式全部失败**(实测失败分子上的触发率是 **100%**)。
//! 它的失败分子与最慢分子高度重合,原因就在这里。
//!
//! **本算法保留嵌入,换掉那一步随机采样。**
//!
//! 关键在 [`smooth`]:Floyd–Warshall 之后的上限矩阵 `U` **本身就是一个度量**
//! (`U_ij ≤ U_ik + U_kj` 按构造恒成立),它是一张"画得出来"的距离表。
//! 直接拿它当参考距离表,在**同一批界矩阵**上与 RDKit 那样的随机取法对照
//! (400 个分子,由 `examples/bounds_oracle.rs` 的判据三每次跑出来):
//!
//! | | 谱:负特征值份额 | 谱:前三特征值占正谱 | **几何:嵌出来越界 >0.1 Å 的对** |
//! |---|---|---|---|
//! | 区间内随机取 | 0.284 | 0.648 | 36.7% |
//! | **直接用 `U`** | **0.042** | **0.930** | **29.3%** |
//!
//! **两栏的差距不一样大,这一点必须说清楚。** 谱上 `U` 好 6.8 倍,几何上只好
//! 1.25 倍。原因是 `U` 让每一对都取到上限 —— 逐对都合法,合在一起却办不到,
//! 于是嵌入把这份做不到的账均摊到所有对上。**谱好看不等于坐标好用**,
//! 判据三因此同时量这两栏,而拿来立论的应当是几何那一栏。
//!
//! `U` 仍然是目前最好的选择(两栏都赢),而且**全程没有随机数** ——
//! 同一个分子永远同一个答案,不需要 seed。至于"有没有比 `U` 更好的参考表"
//! (中点表、部分 metrization……),那要等精修落地、能量端到端的成功率之后再比:
//! 现在换表等于在优化一个代理量。
//!
//! # 曾经走错的两条路(别再走)
//!
//! 1. **按分子类别切分支**(无环走构造法、有环另说、超配位拒绝……):覆盖率停在
//!    14.3%,而且每来一类分子就得加一个分支。
//! 2. **换个便宜初值来砍掉嵌入**(生成树 NeRF 走一遍):实测**慢约 2 倍**,不是快 ——
//!    嵌入不是成本,它给优化器一个好起点,省下的迭代远超那次特征分解。
//!
//! # 通用性的判定标准
//!
//! 新来一类分子(笼状、金属配合物、大环)时,要改的必须是**约束表**,
//! 不是代码分支。嵌入器里不允许出现 `is_macrocycle` / `is_metal` 这类分子类别谓词 ——
//! 这条可以直接 grep 进闸门。

//! # RDKit 那条"作废整次尝试"的规则有多狠
//!
//! `computeInitialCoords` 只要发现**一个**原子的 `sqD0i` 低于阈值就把整次尝试
//! 判死(`DistGeomUtils.cpp:110-115`)。判据三顺手记了这笔账:照搬这条规则,
//! 400 个分子里 `U` 表会被打掉 **265** 个。
//!
//! 这不说明 `U` 差 —— 它的谱与几何两栏都赢 —— 而说明**那条规则本身太粗**:
//! `sqD0i` 是"到质心的平方距离",`U` 把长程距离整体抬高,居中的原子于是算出负值。
//! 那是长程被抬高的症状,不是摆不出来的证据。本算法因此**不作废,只记账**。

