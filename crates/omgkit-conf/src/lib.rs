//! **确定性的分子 3D 初始构型生成** —— 给后续力场优化提供一个起点。
//!
//! # 目标,以及**不是**目标
//!
//! 目标:给一个分子生成**一个**三维构型,键长键角基本合理、立体化学正确、
//! 没有原子重叠,**交给后续力场优化**。
//!
//! **不是**目标:构象系综、构象搜索、接近实验结构、MMFF 优化后的几何分布。
//!
//! # 与 RDKit(ETKDG)的分岔点:**去掉随机采样,不是去掉嵌入**
//!
//! RDKit 的流程是:界矩阵 → 三角光滑化 → **在区间里随机取一组距离** →
//! 度量矩阵嵌入 → 误差函数精修 → 不合格就换一组随机距离重来(最多 `10×N` 次)。
//!
//! 病在"随机取一组距离"这一步:每一对原子**各自独立**取值,取出来的表
//! 往往任何空间里都摆不出来 —— 好比"A 离 B 三米、B 离 C 三米、A 离 C 十米",
//! 写得下来,画不出来。RDKit 的应对是作废整次尝试重掷,而当病因是结构性的时候,
//! **`10×N` 次重试会以同样的方式全部失败**(实测失败分子上的触发率是 **100%**)。
//! 它的失败分子与最慢分子高度重合,原因就在这里。
//!
//! **本算法保留嵌入,换掉那一步随机采样。**
//!
//! 关键在 [`smooth`]:Floyd–Warshall 之后的上限矩阵 `U` **本身就是一个度量**
//! (`U_ij ≤ U_ik + U_kj` 按构造恒成立),它是一张"画得出来"的距离表。
//! 直接拿它当参考距离表,实测(476 个分子):
//!
//! | 参考距离表 | 负特征值占谱质量 | 能装进三维的比例 | 起手误差/原子 中位 |
//! |---|---|---|---|
//! | RDKit 随机取 | 0.268 | 0.662 | 10.20 |
//! | 部分 metrization 跑 60 趟 | 0.207 | 0.708 | 0.91 |
//! | **直接用 `U`** | **0.039** | **0.930** | **0.288** |
//!
//! 一趟光滑化就比 metrization 跑 60 趟更好,而且**全程没有随机数** ——
//! 同一个分子永远同一个答案,不需要 seed。
//!
//! # 曾经走错的两条路(别再走)
//!
//! 1. **按分子类别切分支**(无环走构造法、有环另说、超配位拒绝……):覆盖率停在
//!    14.3%,而且每来一类分子就得加一个分支。
//! 2. **换个便宜初值来砍掉嵌入**(生成树 NeRF 走一遍):实测**慢约 2 倍**,不是快 ——
//!    嵌入不是成本,它给优化器一个好起点,省下的迭代远超那次特征分解。
//!
//! # 通用性的判定标准
//!
//! 新来一类分子(笼状、金属配合物、大环)时,要改的必须是**约束表**,
//! 不是代码分支。嵌入器里不允许出现 `is_macrocycle` / `is_metal` 这类分子类别谓词 ——
//! 这条可以直接 grep 进闸门。

