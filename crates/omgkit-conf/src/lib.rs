//! **分子 3D 初始构型生成** —— 给后续力场优化提供一个起点。
//!
//! # 这个 crate 的目标,以及**不是**目标
//!
//! 目标是:给一个分子生成**一个**三维构型,键长键角基本合理,拓扑与立体化学正确,
//! 没有原子重叠,**交给后续力场优化**。
//!
//! **不是**目标(交给后续优化):接近 MMFF/UFF 优化后的几何分布、挑环的构象族
//! (椅式还是扭船)、扭转角的能量、构象搜索与多构象。
//!
//! # 必须对的四条(力场救不回来的)
//!
//! | 项 | 为什么力场救不回来 |
//! |---|---|
//! | 拓扑 | 键连错了就是别的分子 |
//! | 立体化学 | 手性/EZ 是**离散**的,局部极小化跨不过势垒 —— 摆反了会得到一个能量很低的**错分子** |
//! | 没有重叠/穿插 | 两个原子叠在一起,`1/r¹²` 直接爆掉,优化器起不来;链穿过环更是推不开 |
//! | 覆盖率 | 摆不出来,下游拿到的是个洞 |
//!
//! # 与 RDKit ETKDG 的分岔点
//!
//! ETKDG 对**整个分子**做距离几何:1-2/1-3/1-4 全写成**宽**区间(它要采样多样性),
//! 三角光滑化后随机取一组距离,再对 N×N 做度量矩阵嵌入。
//! 实测全语料 8839 个分子 86.5 s、最慢单分子 8.11 s、失败 46 个(0.52%,含 1 个 C++ 抛异常)。
//! 三个代价都从"全分子 + 随机采样"来。
//!
//! 这里改两处:
//!
//! 1. **只有环需要距离几何,链不需要** —— 链按内坐标直接摆([`geom::place_nerf`]),
//!    `O(N)` 零迭代。DG 的规模从"整分子 30~80 原子"降到"一个环系 5~20 原子",
//!    而特征分解是 `O(N³)`。
//! 2. **区间收窄**(角用参考表的 `p05`/`p95`、键长 ±3%),光滑化后**取中点** ——
//!    不采样、不重试、可复现。
//!
//! **注意不是"钉成等式"**:等式化会让约束系统在规格上必然自相矛盾
//! (三元环内角须恰好和为 180°,实测 94 个全不成立;四配位中心只有 0.29% 精确可实现),
//! 而且 1.51% 的分子在进嵌入前界矩阵就崩 —— 那会把覆盖率天花板压到 98.5%。
//!
//! # 进度
//!
//! 一期(当前):无环 + 单个苯/吡啶环。二期:环系 DG + 模板。三期:消撞。四期:性能。

